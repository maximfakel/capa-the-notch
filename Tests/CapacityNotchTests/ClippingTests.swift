func theShelfTellsDiagnosticsHowManyClippingsNeverWhich() throws {
    var clippings = Clippings()
    clippings.keep("секрет", at: start)
    let said = ShelfModule.observation(enabled: true, shelf: Shelf(), clippings: clippings)
    try expect(said == "shelf-on-0-files-0-screenshots-1-clippings", "Counts only, got \(said)")
