func textIntakeIsOffUntilAskedForAndKeepsADay() throws {
    let suite = "clippings-\(UUID())"
    let defaults = try unwrapClipping(UserDefaults(suiteName: suite))
    defer { defaults.removePersistentDomain(forName: suite) }
    let preferences = Preferences(defaults: defaults)
    try expect(!preferences.shelfKeepsText, "Text intake off until turned on")
    try expect(preferences.clippingLimit == .twenty, "Twenty Clippings")
    try expect(preferences.clippingsExpire, "Each gone after a day")
    try expect(preferences.clipboardExcludedApplications.isEmpty, "No application chosen")
    preferences.clippingLimit = .hundred
    preferences.clippingsExpire = false
    preferences.clipboardExcludedApplications = ["ru.bank.app"]
    let again = Preferences(defaults: defaults)
    try expect(again.clippingLimit == .hundred && !again.clippingsExpire, "Choices are kept")
    try expect(again.clipboardExcludedApplications == ["ru.bank.app"], "and the applications chosen")
}

