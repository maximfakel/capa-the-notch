func fewerChosenTheOldestGoAtOnceAndTheRestStayAsTheyWere() throws {
    var clippings = Clippings()
    for index in 1...30 { clippings.keep("\(index)", at: start.addingTimeInterval(Double(index)), limit: .fifty) }
    let newest = try unwrapClipping(clippings.items.first)
    clippings.trim(to: .twenty)
    try expect(clippings.items.count == 20, "Twenty, got \(clippings.items.count)")
    try expect(clippings.items.first == newest, "The newest unchanged, the same Clipping as before")
    try expect(clippings.items.last?.text == "11", "The oldest gone, got \(clippings.items.last?.text ?? "nothing")")
}
